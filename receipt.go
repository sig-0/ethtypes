package ethtypes

import (
	"errors"
	"fmt"
	"math/big"

	"github.com/sig-0/ethrlp"
	ethProto "github.com/sig-0/ethtypes/proto/eth/v1"
)

var (
	ErrNilProtoReceipt = errors.New("proto receipt is nil")
	ErrNilProtoLog     = errors.New("proto log is nil")

	ErrInvalidLogRLPAddress       = errors.New("invalid log RLP address encoding")
	ErrInvalidLogRLPData          = errors.New("invalid log RLP data encoding")
	ErrInvalidLogRLPTopics        = errors.New("invalid log RLP topics encoding")
	ErrInvalidReceiptRLPStatus    = errors.New("invalid receipt RLP status encoding")
	ErrInvalidReceiptRLPGasUsed   = errors.New("invalid receipt RLP cumulative gas used encoding")
	ErrInvalidReceiptRLPLogsBloom = errors.New("invalid receipt RLP logs bloom encoding")
	ErrInvalidReceiptRLPLogs      = errors.New("invalid receipt RLP logs encoding")
)

// Receipt represents a transaction receipt, which contains information about a transaction
// after it has been processed and included in a block
type Receipt struct {
	Logs              []*Log // List of logs generated by the transaction
	LogsBloom         Bloom  // Bloom filter for logs generated by this transaction
	CumulativeGasUsed uint64 // Total gas used when this transaction was executed
	Status            bool   // true -> 1 (success); false -> 0 (failure)
}

// ToProto converts a Receipt struct to its Protocol Buffer representation
func (r *Receipt) ToProto() *ethProto.Receipt {
	if r == nil {
		return nil
	}

	pb := &ethProto.Receipt{
		CumulativeGasUsed: r.CumulativeGasUsed,
		Status:            r.Status,
	}

	// Convert LogsBloom
	pb.LogsBloom = r.LogsBloom.ToBytes()

	// Convert Logs
	if len(r.Logs) > 0 {
		pb.Logs = make([]*ethProto.Log, len(r.Logs))

		for i, log := range r.Logs {
			pb.Logs[i] = log.ToProto()
		}
	}

	return pb
}

// FromProto converts a proto Receipt to a Receipt
func (r *Receipt) FromProto(pb *ethProto.Receipt) error {
	if pb == nil {
		return ErrNilProtoReceipt
	}

	receipt := &Receipt{
		CumulativeGasUsed: pb.CumulativeGasUsed,
		Status:            pb.Status,
	}

	// Convert the logs bloom
	if pb.LogsBloom != nil {
		receipt.LogsBloom = BytesToBloom(pb.LogsBloom)
	}

	// Convert Logs
	if len(pb.Logs) > 0 {
		receipt.Logs = make([]*Log, len(pb.Logs))

		for i, protoLog := range pb.Logs {
			log := new(Log)
			if err := log.FromProto(protoLog); err != nil {
				return fmt.Errorf("unable to parse log: %w", err)
			}

			receipt.Logs[i] = log
		}
	}

	return nil
}

// ToRLP encodes the receipt using RLP encoding
func (r *Receipt) ToRLP() []byte {
	// Prepare the logs
	encodedLogs := make([][]byte, 0, len(r.Logs))

	for _, log := range r.Logs {
		encodedLogs = append(
			encodedLogs,
			log.ToRLP(),
		)
	}

	rlpPayload := [][]byte{
		ethrlp.EncodeBool(r.Status),
		ethrlp.EncodeUint(r.CumulativeGasUsed),
		ethrlp.EncodeBytes(r.LogsBloom.ToBytes()),
		ethrlp.EncodeArray(encodedLogs),
	}

	return ethrlp.EncodeArray(rlpPayload)
}

// FromRLP parses the RLP encoding of a receipt
func (r *Receipt) FromRLP(data []byte) error {
	// Decode the RLP data
	list, err := ethrlp.DecodeBytes(data)
	if err != nil {
		return fmt.Errorf("failed to decode receipt RLP data: %w", err)
	}

	if list.GetType() != ethrlp.List {
		return fmt.Errorf("invalid receipt RLP encoding type: %s", list.GetType())
	}

	// Extract the list RLP values
	listValues, _ := list.GetValue().([]ethrlp.Value)
	if len(listValues) != 4 {
		return fmt.Errorf(
			"invalid receipt RLP encoding length: %d, expected %d",
			len(listValues),
			4,
		)
	}

	// Decode the status
	if listValues[0].GetType() != ethrlp.Bytes {
		return fmt.Errorf(
			"invalid RLP encoding type for status, %s",
			listValues[0].GetType(),
		)
	}

	statusRaw, ok := listValues[0].GetValue().([]byte)
	if !ok || statusRaw == nil {
		return ErrInvalidReceiptRLPStatus
	}

	statusBig := big.NewInt(0).SetBytes(statusRaw)
	r.Status = statusBig.Uint64() == 1

	// Decode the cumulative gas used
	if listValues[1].GetType() != ethrlp.Bytes {
		return fmt.Errorf(
			"invalid RLP encoding type for cumulative gas used, %s",
			listValues[1].GetType(),
		)
	}

	cumulativeGasUsedRaw, ok := listValues[1].GetValue().([]byte)
	if !ok || cumulativeGasUsedRaw == nil {
		return ErrInvalidReceiptRLPGasUsed
	}

	cumulativeGasUsed := big.NewInt(0).SetBytes(cumulativeGasUsedRaw)
	r.CumulativeGasUsed = cumulativeGasUsed.Uint64()

	// Decode the logs bloom
	if listValues[2].GetType() != ethrlp.Bytes {
		return fmt.Errorf(
			"invalid RLP encoding type for logs bloom, %s",
			listValues[2].GetType(),
		)
	}

	logsBloomRaw, ok := listValues[2].GetValue().([]byte)
	if !ok || logsBloomRaw == nil {
		return ErrInvalidReceiptRLPLogsBloom
	}

	r.LogsBloom = BytesToBloom(logsBloomRaw)

	// Decode the logs
	if listValues[3].GetType() != ethrlp.List {
		return fmt.Errorf(
			"invalid RLP encoding type for logs, %s",
			listValues[3].GetType(),
		)
	}

	logsListRaw, ok := listValues[3].GetValue().([]ethrlp.Value)
	if !ok || logsListRaw == nil {
		return ErrInvalidReceiptRLPLogs
	}

	logs := make([]*Log, 0, len(logsListRaw))

	for _, logRaw := range logsListRaw {
		if logRaw.GetType() != ethrlp.Bytes {
			return errors.New("invalid receipt log entry RLP encoding")
		}

		encodedLog, ok := logRaw.GetValue().([]byte)
		if !ok || encodedLog == nil {
			return errors.New("invalid receipt log entry RLP encoding")
		}

		log := new(Log)
		if err = log.FromRLP(encodedLog); err != nil {
			return fmt.Errorf("invalid receipt log entry RLP encoding: %w", err)
		}

		logs = append(logs, log)
	}

	r.Logs = logs

	return nil
}

// Log are a mechanism for smart contracts to emit structured data
// during their execution
type Log struct {
	Topics  []Hash  // the topics referenced in the log
	Data    []byte  // the data contained in the log (event data)
	Address Address // the originating address of the event (SC)
}

// ToProto converts a Log to its proto representation
func (l *Log) ToProto() *ethProto.Log {
	if l == nil {
		return nil
	}

	pb := &ethProto.Log{
		Data:    l.Data,
		Address: l.Address.ToBytes(),
	}

	// Convert Topics
	if len(l.Topics) > 0 {
		pb.Topics = make([][]byte, len(l.Topics))

		for i, topic := range l.Topics {
			pb.Topics[i] = topic.ToBytes()
		}
	}

	return pb
}

// FromProto converts a proto Log to a Log
func (l *Log) FromProto(pb *ethProto.Log) error {
	if pb == nil {
		return ErrNilProtoLog
	}

	log := &Log{
		Data: pb.Data,
	}

	// Convert Address
	if len(pb.Address) > 0 {
		log.Address = BytesToAddress(pb.Address)
	}

	// Convert Topics
	if len(pb.Topics) > 0 {
		log.Topics = make([]Hash, len(pb.Topics))

		for i, topic := range pb.Topics {
			log.Topics[i] = BytesToHash(topic)
		}
	}

	return nil
}

// ToRLP encodes the Log using RLP encoding
func (l *Log) ToRLP() []byte {
	// Prepare the topics
	encodedTopics := make([][]byte, 0, len(l.Topics))

	for _, topic := range l.Topics {
		encodedTopics = append(
			encodedTopics,
			ethrlp.EncodeBytes(topic.ToBytes()),
		)
	}

	rlpPayload := [][]byte{
		ethrlp.EncodeBytes(l.Address.ToBytes()),
		ethrlp.EncodeArray(encodedTopics),
		ethrlp.EncodeBytes(l.Data),
	}

	return ethrlp.EncodeArray(rlpPayload)
}

// FromRLP parses the RLP encoding of a log
func (l *Log) FromRLP(data []byte) error {
	// Decode the RLP data
	list, err := ethrlp.DecodeBytes(data)
	if err != nil {
		return fmt.Errorf("failed to decode log RLP data: %w", err)
	}

	if list.GetType() != ethrlp.List {
		return fmt.Errorf("invalid log RLP encoding type: %s", list.GetType())
	}

	// Extract the list RLP values
	listValues, _ := list.GetValue().([]ethrlp.Value)
	if len(listValues) != 3 {
		return fmt.Errorf(
			"invalid log RLP encoding length: %d, expected %d",
			len(listValues),
			3,
		)
	}

	// Decode the address
	if listValues[0].GetType() != ethrlp.Bytes {
		return fmt.Errorf(
			"invalid RLP encoding type for address, %s",
			listValues[0].GetType(),
		)
	}

	addressRaw, ok := listValues[0].GetValue().([]byte)
	if !ok || addressRaw == nil {
		return ErrInvalidLogRLPAddress
	}

	l.Address = BytesToAddress(addressRaw)

	// Decode the topics
	if listValues[1].GetType() != ethrlp.List {
		return fmt.Errorf(
			"invalid RLP encoding type for topics, %s",
			listValues[1].GetType(),
		)
	}

	topicValues, ok := listValues[1].GetValue().([]ethrlp.Value)
	if !ok || listValues == nil {
		return ErrInvalidLogRLPTopics
	}

	topics := make([]Hash, 0, len(topicValues))

	for _, topicRaw := range topicValues {
		if topicRaw.GetType() != ethrlp.Bytes {
			return errors.New("invalid log topic RLP encoding")
		}

		topic, ok := topicRaw.GetValue().([]byte)
		if !ok || topic == nil {
			return errors.New("invalid log topic RLP encoding")
		}

		topics = append(topics, BytesToHash(topic))
	}

	l.Topics = topics

	// Decode the data
	if listValues[2].GetType() != ethrlp.Bytes {
		return fmt.Errorf(
			"invalid RLP encoding type for data, %s",
			listValues[2].GetType(),
		)
	}

	dataRaw, ok := listValues[2].GetValue().([]byte)
	if !ok || dataRaw == nil {
		return ErrInvalidLogRLPData
	}

	l.Data = dataRaw

	return nil
}
